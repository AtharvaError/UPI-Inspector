export function money(n: number | string | null | undefined): string {
  const v = Math.round(Number(n || 0) * 100) / 100;
  const neg = v < 0;
  const [whole, frac] = Math.abs(v).toFixed(2).split(".");
  let head = whole;
  let out = "";
  if (head.length > 3) {
    out = "," + head.slice(-3);
    head = head.slice(0, -3);
    while (head.length > 2) {
      out = "," + head.slice(-2) + out;
      head = head.slice(0, -2);
    }
  }
  const s = head + out + (frac === "00" ? "" : "." + frac);
  return (neg ? "-" : "") + s;
}

