export function clock(d: Date | string | number): string {
  const x = new Date(d);
  let h = x.getHours();
  const m = x.getMinutes();
  const ap = h >= 12 ? "pm" : "am";
  h = h % 12 || 12;
  return `${h}:${m < 10 ? "0" : ""}${m} ${ap}`;
}

export function dateTime(d: Date | string | number, locale = "en"): string {
  const x = new Date(d);
  if (isNaN(x.getTime())) return "";
  const mon = (MON as any)[locale] || MON.en;
  return `${x.getDate()} ${mon[x.getMonth()]}, ${clock(x)}`;
}

export function duration(seconds: number, locale = "en"): string {
  const s = Math.max(0, Math.round(seconds));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const r = s % 60;
  const u = locale === "hi" ? { h: "घं", m: "मि", s: "से" } : { h: "h", m: "min", s: "s" };
  if (h > 0) return `${h} ${u.h} ${m} ${u.m}`;
  if (m > 0) return `${m} ${u.m} ${r < 10 ? "0" : ""}${r} ${u.s}`;
  return `${r} ${u.s}`;
}

/** A length of time in words, to the nearest sensible unit: "3 days", "24 hours". For ages and waiting
 *  times; `duration` above is for countdowns. */
export function span(seconds: number, locale = "en"): string {
  const s = Math.max(0, seconds);
  const hi = locale === "hi";
  const say = (n: number, one: string, many: string, h: string) => (hi ? `${n} ${h}` : `${n} ${n === 1 ? one : many}`);
  if (s < 90) return say(Math.round(s), "second", "seconds", "सेकंड");
  if (s < 90 * 60) return say(Math.round(s / 60), "minute", "minutes", "मिनट");
  if (s < 36 * 3600) return say(Math.round(s / 3600), "hour", "hours", "घंटे");
  const d = Math.round(s / 86400);
  if (d < 60) return say(d, "day", "days", "दिन");
  if (d < 730) return say(Math.round(d / 30), "month", "months", "महीने");
  return say(Math.round(d / 365), "year", "years", "साल");
}

export function mmss(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds));
  const m = Math.floor(s / 60);
  const r = s % 60;
  return `${m < 10 ? "0" : ""}${m}:${r < 10 ? "0" : ""}${r}`;
}

export function initials(name: string | undefined | null): string {
  const parts = (name || "?").trim().split(/\s+/).filter(Boolean);
  return ((parts[0]?.[0] || "?") + (parts.length > 1 ? parts[parts.length - 1][0] : "")).toUpperCase();
}

