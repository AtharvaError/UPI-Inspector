const DICTS: Record<string, Dict> = { en: EN, hi: HI };

export function translate(locale: string, key: string, vars?: Record<string, string | number>): string {
  let s = (DICTS[locale] || EN)[key];
  if (s === undefined) s = EN[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** `t` for the signed-in user's language, with the text scale for the large-text setting. */
export function useT() {
  const locale = useAppSelector((s) => s.session.locale);
  const large = useAppSelector((s) => !!s.session.me?.large_text);
  const t = useCallback((key: string, vars?: Record<string, string | number>) => translate(locale, key, vars), [locale]);
  return { t, locale, scale: large ? 1.3 : 1 };
}

